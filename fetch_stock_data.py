"""Fetch Yahoo Finance metadata and rebuild the hardcoded teaching data.

Run with .venv/bin/python fetch_stock_data.py. This needs internet access.
The normal database creation example uses stock_data.py without internet access.
"""

import csv
import json
from datetime import datetime, timezone
from pathlib import Path
from pprint import pformat
import time

import yfinance as yf

FOLDER = Path(__file__).resolve().parent
# The first six entries are the companies requested for this example.
TICKERS = [
    "TSLA", "SPCX", "AMZN", "NVDA", "KO", "F", "AAPL", "MSFT", "GOOGL", "META",
    "NFLX", "JPM", "V", "WMT", "DIS", "NKE", "MCD", "PEP", "INTC", "AMD",
]
FIELDS = ["ticker", "country", "currency", "company_name", "company_info", "category"]


def fetch_records():
    """Fetch and validate every company before changing any saved data."""
    records = []
    evidence = []
    for ticker in TICKERS:
        print(f"Fetching Yahoo Finance metadata: {ticker}", flush=True)
        # get_info returns a dictionary. See the library's official documentation:
        # https://ranaroussi.github.io/yfinance/reference/api/yfinance.Ticker.get_info.html
        info = yf.Ticker(ticker).get_info()
        # Map Yahoo's names to the six columns in our SQLite table.
        record = {
            "ticker": ticker,
            "country": info.get("country"),
            "currency": info.get("currency"),
            "company_name": info.get("longName") or info.get("shortName"),
            "company_info": info.get("longBusinessSummary"),
            "category": info.get("sector"),
        }
        missing = [field for field, value in record.items() if not value]
        if missing:
            raise ValueError(f"{ticker}: Yahoo Finance is missing {missing}")
        if info.get("symbol") != ticker or info.get("quoteType") != "EQUITY":
            raise ValueError(f"{ticker}: response is not the requested stock")
        records.append(record)
        evidence.append({"url": f"https://finance.yahoo.com/quote/{ticker}/profile/",
                         "info": info})
        # Space requests out instead of sending all of them together.
        time.sleep(1)
    return records, evidence


def main():
    records, evidence = fetch_records()
    fetched_at = datetime.now(timezone.utc).isoformat()
    # This file is the source evidence for the generated Python and CSV examples.
    evidence_path = FOLDER / "docs" / "stock_metadata_source.json"
    evidence_path.parent.mkdir(exist_ok=True)
    evidence_path.write_text(json.dumps({
        "fetched_at_utc": fetched_at, "yfinance_version": yf.__version__,
        "companies": evidence,
    }, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    # Generate literal Python tuples, so the creation example needs no network.
    rows = [tuple(record[field] for field in FIELDS) for record in records]
    header = (
        '"""Real Yahoo Finance metadata fetched with yfinance.\n\n'
        'Generated by fetch_stock_data.py. Rebuild with that script, rather than edit.\n'
        f'Fetched at UTC: {fetched_at}\n'
        'Source evidence: docs/stock_metadata_source.json\n'
        '"""\n\n'
        '# Each tuple contains ticker, country, currency, company_name,\n'
        '# company_info (Yahoo business summary), and category (Yahoo sector).\n'
    )
    (FOLDER / "stock_data.py").write_text(
        header + "SAMPLE_STOCKS = " + pformat(rows, width=100) + "\n", encoding="utf-8")
    # CSV does not have a standard comment syntax. Its columns are explained above.
    with (FOLDER / "sample_stocks.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows(records)
    print(f"Saved {len(records)} real companies to stock_data.py and sample_stocks.csv")


if __name__ == "__main__":
    main()
